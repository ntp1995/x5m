function fcPlayLottie(target, key, opts) {
    const el = typeof target === 'string' ? document.getElementById(target) : target;
    if (!el) return;
    const o = opts || {};
    const size = o.size || 56;
    el.innerHTML = '';
    el.style.width = size + 'px';
    el.style.height = size + 'px';
    el.style.display = 'inline-flex';
    el.style.alignItems = 'center';
    el.style.justifyContent = 'center';
    if (typeof window !== 'undefined' && window.lottie && typeof window.lottie.loadAnimation === 'function' && FC_LOTTIE_DATA[key]) {
        try {
            window.lottie.loadAnimation({
                container: el,
                renderer: 'svg',
                loop: o.loop !== false,
                autoplay: true,
                animationData: JSON.parse(JSON.stringify(FC_LOTTIE_DATA[key]))
            });
            return;
        } catch (e) {}
    }
    const fallbackIcon = key === 'celebrate' ? 'trophy' : (key === 'scan' ? 'camera' : (key === 'empty' ? 'sparkles' : 'activity'));
    const fallbackColor = key === 'celebrate' ? '#10b981' : (key === 'scan' ? '#f97316' : '#3b82f6');
    el.innerHTML = fcIcon(fallbackIcon, { size: Math.round(size * 0.65), color: fallbackColor, pulse: true });
}
